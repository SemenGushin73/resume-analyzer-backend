package ru.kata.project.model;

/**
 * Перечисления типов событий
 **/
public enum SubscriptionEventType {
    /**
     * Событие, когда подписка или операция с ней была инициирована.
     * Используется для записи факта начала процесса (создание, отмена, обновление).
     * Дополнительные детали в поле 'meta'.
     */
    INITIATED,

    /**
     * Событие, когда подписка или операция с ней успешно завершена.
     * Например: успешное создание подписки, успешная активация, успешная отмена.
     * Статус подписки (ACTIVE, CANCELLED) должен отражать результат.
     * Дополнительные детали в поле 'meta'.
     */
    COMPLETED,

    /**
     * Событие, когда подписка или операция с ней завершилась с ошибкой.
     * Например: неудачная попытка создания, ошибка при отмене, сбой платежа.
     * Статус подписки (CANCELLED) должен отражать, что подписка недействительна.
     * Дополнительные детали об ошибке в поле 'meta'.
     */
    FAILED
}